package model

// DeliverableGateMarker 是「交付物门禁」条款的标题前缀，由引擎自己注入到任务 prompt 里。
//
// 为什么要有这个常量（round 135 · T88）：引擎侧要知道「这个任务是不是被要求交一份报告文件」，
// 而唯一可靠的依据就是它当初写进 prompt 的那句话。此前这句话只以字面量存在于两个包里
// （templates.deliverableGateClause 与 autonomy.autonomyDeliverableGate，标题措辞还略有不同），
// 引擎若自己再抄一份就成了第三份私有清单 —— 改了注入侧忘了判定侧就会静默失效
// （本会话同族病：T57/T61/T72/T80/T84/T86 全是"同一契约多处实现"）。
// ⇒ 单点放这里（templates 与 autonomy 都只依赖 model，不造成任何循环）。
//
// 取值是两侧标题的**共同前缀**："## 交付物门禁"，因此注入侧无论怎么补后缀，判定侧都认得。
// 注意：不要用任务标题的词族（报告/审查/体检…）当判据 —— 实测那是 1,120:5 的口径
// （命中面巨大而真缺陷只有 5 条），会把没打算交报告的模板任务一起判红。
const DeliverableGateMarker = "## 交付物门禁"

// GatePlacementClause 是「探查产物落点」条款的**正文**（不含列表编号），由两处注入点共用：
// templates 侧作为第 6 条、autonomy 侧作为第 7 条 —— 编号是各自列表的自然序号，正文必须同文。
//
// 为什么收进 model（round 166 · T114）：交付物门禁的**标题**早就单点在这里，但条款正文历来两处
// 各写一份（marker 的注释就记载了此事）。我一开始也是两处各写一遍、再打算写一条判据去钉"别漂" ——
// 那是用判据补偿架构缺陷：漂移要等到判据跑起来才发现，而单点定义让它在编译期就不可能发生。
// 本仓在册病 T57/T61/T72/T80/T84/T86 全是"同一契约多处实现"，这次不再添一处。
//
// 为什么必须有这条：external 模式下任务 cwd 就是**被审查的项目根**（executor.go:385-391、:416
// 的 cmd.Dir = workDir），模型随手写的探查脚本会直接落在项目根上，污染被审查的工作空间
// （实测 10 个未跟踪散件：explore.ps1 / probe.py / list_files.py / nul …，git status 长期有噪声）。
// `> nul` 这类 Windows 写法在 bash 下还会把 nul 生成**真实文件**，而 nul 是 Windows 保留设备名。
//
// ⚠️ 末句「交付物不在此列」是承重的、不可删：前 5 条要求报告写进 docs/，若这条只说"临时产物
// 写临时目录"，模型可能把**报告**也写进临时目录 ⇒ 反被 T88 交付物门禁判红（本轮取证时专门核过这条歧义）。
const GatePlacementClause = "**探查用的临时脚本与重定向输出**写到系统临时目录（或任务自己的 scratch 子目录），不要留在被审查的项目根；\n" +
	"   不要用 `> nul` 这类写法（bash 下会生成名为 nul 的真实文件）。**交付物不在此列**：报告仍必须按第 1 条写到 docs/。"
