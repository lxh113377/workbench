// deliverableGateClause 是所有 md 模板共用的**交付物门禁条款**（round 70 · 模板与门禁同口径）。
//
// 为什么需要它（live 实测，2026-10-29）：引擎侧在 round 65/66/69 依次立了三道门禁 ——
//
//	· 报告内容门禁（T66）：`docs/` 下的报告必须含 `## 结论`/`## 证据`/`## 门禁建议` 三节，证据节要有 文件:行号 或可复跑命令；
//	· 分级门禁（T67）：报告必须分级；
//	· 代码产物最小实质（T73）：太小不算交付。
//
// 而模板库的 prompt **一条都没要求**这些 ⇒ 模板任务的产物必然被自己的门禁判红（白跑一次真实执行）。
// 线上实测：4 条模板里 3 条缺「文件:行号/分级/docs/」。
//
// 为什么在构造器单点注入而不是逐条改 prompt：模板库有近 30 条，手改必漏（本轮就是被审计逮到的）；
// 单点注入 + `TestBuiltinMdTemplatesCarryDeliverableGate` 契约测试，才能保证「模板库整体与门禁同口径」不会再次漂移。
// 标题前缀取 model.DeliverableGateMarker：引擎侧的交付物判定（T88）读的就是这个前缀。
// 在这里写死字面量会让「注入侧改了、判定侧不知道」成为可能（本会话同族病的标准形态）。
const deliverableGateClause = "\n\n" + model.DeliverableGateMarker + "（硬性，与引擎判据同口径）\n" +
	"1. 交付物是**文件**不是聊天正文：按产物协议输出产物块，把报告写到 `docs/` 下（例：`docs/五轴审查-<主题>.md`）。\n" +
	"2. 报告必须含三节，标题逐字一致：`## 结论`、`## 证据`、`## 门禁建议`。\n" +
	"3. 「证据」节每条都要带 **文件:行号** 或一条**可复跑命令**；禁止「经检查」「可以发现」这类无证据表述。\n" +
	"4. 必须**分级**：每个发现都标严重度（`P0 阻塞` / `P1 应改` / `P2 建议`，或 高/中/低）。\n" +
	"5. verify 至少 1 条**检查报告内容**的命令（例如按标题与 文件:行号 做断言）；不要拿「运行你自己刚写的脚本」当唯一验收。\n" +
	// 第 6 条（round 166 · T114）：探查产物落点。正文单点在 model.GatePlacementClause（两处共用）。
	"6. " + model.GatePlacementClause + "\n" +
	// 第 7 条（round 184 · 反虚构）：正文同样单点在 model，防两处漂移（与 T114 同法）。
	"7. " + model.GateEvidenceGroundingClause + "\n"

// Defaults 返回内置的 29 条持续产出模板（7 领域；quality 领域 2026-10-24 round 88/90 新增，含五轴审查）。
// 设计原则：每条都必须能独立产出真实可用的成果物，且彼此有逻辑递进关系。

// Defaults 是内置模板的**组合入口**：只负责把各领域分组拼起来，不放具体条目。
//
// 为什么拆（2026-11-01 round 177，对应五轴报告 P1-1）：原实现是**单函数 491 行**，29 个 mk(...) 条目
// 全在同一个切片字面量里。函数内其实已有 7 个「── 领域分组」注释，但形状上仍是一坨：改任一模板正文
// 要滚动数百行才能确认上下文，评审 diff 时无法一屏看全 ⇒ 漏看率高。
// 现在每个领域一个函数（defaultsContent / defaultsCode / …），本函数只做 append 拼接。
//
// 为什么这是**纯机械拆分**（可证）：mk 的构造逻辑原样提升为 newMk(now)，mkSpec / deliverableGateClause
// 未动，各条目的**求值顺序与内容逐字不变** ⇒ 8 处既有契约测试（chain_link_contract / deliverable_gate_contract /
// encoded_lessons_contract / placement_clause_contract / quality_pack_contract / templates_test 及 chain 包两处）
// 继续按字段真值兜底。拆分只改变代码形状，不改变任何可观察行为。
func Defaults() []tpl {
	now := model.Now()
	var all []tpl
	all = append(all, defaultsContent(now)...)
	all = append(all, defaultsCode(now)...)
	all = append(all, defaultsKnowledge(now)...)
	all = append(all, defaultsData(now)...)
	all = append(all, defaultsSolution(now)...)
	all = append(all, defaultsReport(now)...)
	all = append(all, defaultsQuality(now)...)
	all = append(all, defaultsFiveAxis(now)...)
	return all
}

// newMk 返回「用 now 固化创建/更新时间」的模板构造器。
//
// 为什么提成包级函数而不是各分组里重复定义闭包：29 个条目都走这一个构造器，
// 交付物门禁子句（deliverableGateClause）与 TemplateParams 的默认值**只此一处**定义 ——
// 若每个分组各写一份闭包，就会出现「同一契约多处实现」漂移（本仓在册病 T57/T61/T72/T80/T84/T86）。
func newMk(now int64) func(id, name, domain, desc, prompt string, tags []string, valuePrior, costPrior float64, weigh int, out spec, chain []string) tpl {
	return func(id, name, domain, desc, prompt string, tags []string, valuePrior, costPrior float64, weigh int, out spec, chain []string) tpl {
		// 交付物门禁单点注入（round 70）：md 模板一律带上「落盘 docs/ + 三节逐字 + 证据形态 + 分级」四要件，
		// 与引擎侧 T66/T67/T73 三道门禁逐条对齐 —— 模板要求的，正是门禁要查的。
		if out.Format == "md" {
			prompt = prompt + deliverableGateClause
		}
		return tpl{
			ID: id, Name: name, Domain: domain, Description: desc,
			PromptTemplate:  prompt,
			Params:          model.TemplateParams{ModelTier: "balanced", MaxMinutes: 30, OutputFormat: out.Format, WebAllowed: false, Tags: tags},
			OutputSpec:      out,
			PriorityWeight:  weigh,
			ValuePrior:      valuePrior,
			CostPrior:       costPrior,
			CooldownMinutes: 60,
			DiversityGroup:  domain,
			Chain:           model.ChainSpec{SuccessorTemplates: chain, MaxDepth: 5, Fanout: 2},
			Enabled:         true,
			Builtin:         true,
			CreatedAt:       now,
			UpdatedAt:       now,
		}
	}
}

